def цена_текстом(число):
    return "{:,}".format(int(число)).replace(",", " ") + " ₽"


def главная():
    os.chdir(os.path.dirname(os.path.abspath(__file__)))
    with open("товары.json", encoding="utf-8") as файл:
        данные = json.load(файл)

    с_выбором = 0
    for товар in данные["товары"]:
        запись = ВЫБОР.get(товар["id"])
        if not запись:
            товар.pop("варианты", None)
            товар.pop("строка_выбора", None)
            continue
        строка, варианты = запись

        товар["варианты"] = [{"имя": имя, "цена": цена, "от": от}
                             for имя, цена, от in варианты]
        товар["строка_выбора"] = строка
        # в каталоге и фильтре товар стоит столько, сколько его дешёвая версия
        товар["цена"] = min(ц for _, ц, _ in варианты)
        if len(варианты) > 1:
            товар["цена_от"] = True
            с_выбором += 1
        else:
            товар.pop("цена_от", None)

        # характеристику приводим в соответствие: перечисляем все варианты
        перечень = " / ".join(и for и, _, _ in варианты)
        нашлась = False
        for пара in товар.get("характеристики", []):
            if пара[0] == строка:
                пара[1] = перечень
                нашлась = True
        if not нашлась:
            print("  !  %s: строки «%s» нет в характеристиках" % (товар["id"], строка))

    with open("товары.json", "w", encoding="utf-8") as файл:
        json.dump(данные, файл, ensure_ascii=False, indent=2)

    print("\n  Товаров с выбором: %d" % с_выбором)
    for товар in данные["товары"]:
        if товар.get("варианты") and len(товар["варианты"]) > 1:
            print("    %-22s %s" % (товар["имя"], ", ".join(
                "%s — %s%s" % (в["имя"], "от " if в["от"] else "", цена_текстом(в["цена"]))
                for в in товар["варианты"])))
    print()


if __name__ == "__main__":
    главная()
