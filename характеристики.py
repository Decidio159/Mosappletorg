def главная():
    os.chdir(os.path.dirname(os.path.abspath(__file__)))
    with open("товары.json", encoding="utf-8") as файл:
        данные = json.load(файл)

    пропущены, заглушек, строк = [], 0, 0
    for товар in данные["товары"]:
        запись = ДАННЫЕ.get(товар["id"])
        if not запись:
            пропущены.append(товар["id"])
            continue
        таблица, подробно = запись
        порядок = ПОРЯДОК[товар["тип"]]
        лишние = set(таблица) - set(порядок)
        нехватка = set(порядок) - set(таблица)
        if лишние:
            print("  !  %s: строки не из порядка типа — %s" % (товар["id"], ", ".join(лишние)))
        if нехватка:
            print("  !  %s: не заполнены — %s" % (товар["id"], ", ".join(нехватка)))
        товар["характеристики"] = [[имя, таблица[имя]] for имя in порядок if имя in таблица]
        товар["подробно"] = подробно
        строк += len(товар["характеристики"])
        заглушек += sum(1 for _, з in товар["характеристики"] if з == СПРОСИМ)

    with open("товары.json", "w", encoding="utf-8") as файл:
        json.dump(данные, файл, ensure_ascii=False, indent=2)

    print("\n  Характеристики: %d товаров, %d строк" % (len(данные["товары"]) - len(пропущены), строк))
    if пропущены:
        print("  Без характеристик: %s" % ", ".join(пропущены))
    print("  Строк «%s»: %d — производитель их не публикует\n" % (СПРОСИМ, заглушек))


if __name__ == "__main__":
    главная()
