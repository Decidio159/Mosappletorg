/* =========================================================
   ДЕМО-РЕЖИМ ФОРМЫ — только для макета, до договорённости.

   Подключается на макете, который лежит без PHP: тогда форма
   не пытается никуда отправлять, а показывает «заявка принята»
   и очищается. Клиент видит, что форма живая, а вам не приходят
   письма от собственных проверок.

   Если макет лежит на хостинге с PHP, этот файл НЕ подключается:
   send.php работает по-настоящему, письма идут на почту из $TO,
   и пятый пункт чеклиста («форма отправляется») проверяется всерьёз.

   При сдаче файл убирается — это делает инструменты/сдача.py.
   ========================================================= */

(function () {
  "use strict";

  // Флаг читает form.js в момент отправки, поэтому порядок подключения не важен.
  window.МАКЕТ_ДЕМО = true;

  // Подпись под каждой формой, чтобы демо-режим не выглядел как настоящая отправка
  // для того, кто будет проверять макет вместе с вами.
  document.addEventListener("DOMContentLoaded", function () {
    var формы = document.querySelectorAll("form[data-form]");
    Array.prototype.forEach.call(формы, function (форма) {
      var подпись = форма.querySelector(".form__note");
      if (!подпись) {
        подпись = document.createElement("p");
        подпись.className = "form__note";
        форма.appendChild(подпись);
      }
      подпись.textContent = "Макет: заявка показывается, но не отправляется. "
        + "На готовом сайте письмо приходит на почту за секунду.";
    });
  });
})();
